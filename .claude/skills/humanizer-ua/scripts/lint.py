#!/usr/bin/env python3
"""Детермінований лінтер AI-слопу для humanizer-ua.

Usage:
    python3 scripts/lint.py file.md          # or stdin: python3 scripts/lint.py < file.md
    python3 scripts/lint.py --self-test      # run the fixture suite
    python3 scripts/lint.py --json file.md   # machine-readable output

Classes:
    ARTIFACT  copy-paste residue from a chatbot. One hit is a verdict on its own.
    ERROR     hard bans from SKILL.md. Gate: exit 1, the text is not finished.
    WARN      pattern markers. Evidence only in clusters. Exit 0.

Run the linter on the FINAL text only, never on a draft that still quotes
"before" examples: a quoted violation is a citation, not a defect. Fenced code,
inline backticks and URLs are stripped before prose rules run, so an artifact
shown in backticks does not count.

Verdict: errors * 3 + warnings -> clean (0-3) / review (4-10) / rewrite (11+).
"""
import argparse
import json
import re
import sys

# --- text preparation -------------------------------------------------------

FRONTMATTER = re.compile(r"\A---\r?\n.*?\r?\n---\r?\n", re.S)
CODE_BLOCK = re.compile(r"```.*?```|~~~.*?~~~|`[^`\n]+`", re.S)
URL = re.compile(r"https?://\S+|\bwww\.\S+")


NON_NEWLINE = re.compile(r"[^\n]")


def blank(match):
    """Erase a span but keep its newlines, so reported line numbers stay true."""
    return NON_NEWLINE.sub(" ", match.group(0))


def strip_frontmatter(text):
    """Blank YAML frontmatter. It is metadata, not prose."""
    return FRONTMATTER.sub(blank, text)


def strip_code(text):
    """Blank fenced blocks and inline code, keeping offsets stable."""
    return CODE_BLOCK.sub(blank, text)


QUOTED_SPAN = re.compile(
    "|".join([
        "«[^»\n]{0,400}»",   # «guillemets»
        "„[^“\n]{0,400}“",   # „german low-high“
        "“[^”\n]{0,400}”",   # “curly”
        '"[^"\n]{0,400}"',                   # "straight"
    ])
)
BLOCKQUOTE = re.compile(r"(?m)^\s{0,3}>.*$")


def quotes_of(text):
    """Prose view with quoted material removed.

    Quoting a marker is not using one. A journalist reporting a politician
    verbatim, an essay about AI writing that cites the phrases it studies, a
    style guide showing specimens - all contain watched phrases that must
    survive untouched. The upstream skill says the same: do not rewrite watched
    phrases inside quotations, titles, or examples where the phrase is being
    discussed rather than used.

    Typography rules opt out of this view, because a quotation mark inside a
    quotation is the quotation, not a mention of one.
    """
    body = BLOCKQUOTE.sub(blank, text)
    return QUOTED_SPAN.sub(blank, body)


def prose_of(text):
    """Prose view: no frontmatter, no code, no URLs."""
    return URL.sub(blank, strip_code(strip_frontmatter(text)))


def views_of(text):
    """Build the three text views once per document.

    artifact  everything except code, URLs kept
    raw       prose without code or URLs, quotations kept
    prose     the default: raw, minus quoted material
    """
    raw = prose_of(text)
    return {"artifact": raw_of(text), "raw": raw, "prose": quotes_of(raw)}


def raw_of(text):
    """Artifact view: no frontmatter, no code, but URLs kept.

    Chatbot artifacts hide inside URLs (utm_source=chatgpt.com), so this view
    keeps them. Backticked artifacts are still excluded: quoting an artifact is
    how you discuss it, not how you leak it.
    """
    return strip_code(strip_frontmatter(text))


