def _compile(rules):
    out = []
    for rule in rules:
        try:
            out.append((rule["code"], rule["description"], re.compile(rule["regex"]), rule))
        except re.error as exc:  # pragma: no cover - guarded by self-test
            print("lint.py: rule %s has an invalid regex: %s" % (rule["code"], exc), file=sys.stderr)
            raise SystemExit(2)
    return out


def line_of(text, index):
    return text.count("\n", 0, index) + 1


def _scan(rules, views, severity):
    found = []
    for code, description, rx, rule in _compile(rules):
        if severity == "ARTIFACT":
            text = views["artifact"]
        else:
            text = views["raw"] if rule.get("scope") == "raw" else views["prose"]
        for m in rx.finditer(text):
            quote = m.group(0).strip()
            if not quote:
                continue
            found.append({
                "severity": severity,
                "code": code,
                "description": description,
                "line": line_of(text, m.start()),
                "quote": quote[:120],
            })
    return found


def lint(text, allow=()):
    """Return findings for one document, ordered by line.

    allow: rule codes to switch off. The skill bans dashes in its own output,
    but that ban carries an exemption - a writer whose own sample uses dashes
    keeps them. Passing the rule code here is how that exemption is honoured
    without editing the rule table.
    """
    allow = {code.strip().upper() for code in allow if code.strip()}
    views = views_of(text)
    findings = []
    findings += _scan(ARTIFACTS, views, "ARTIFACT")
    findings += _scan(ERRORS, views, "ERROR")
    findings += _scan(WARNINGS, views, "WARN")
    if allow:
        findings = [f for f in findings if f["code"].upper() not in allow]
    findings.sort(key=lambda f: (f["line"], f["code"]))
    return findings


def verdict(findings):
    """Score the document. Any artifact is decisive on its own."""
    artifacts = [f for f in findings if f["severity"] == "ARTIFACT"]
    errors = [f for f in findings if f["severity"] == "ERROR"]
    warnings = [f for f in findings if f["severity"] == "WARN"]
    if artifacts:
        return "rewrite", 100, artifacts, errors, warnings
    score = len(errors) * 3 + len(warnings)
    if score <= 3:
        label = "clean"
    elif score <= 10:
        label = "review"
    else:
        label = "rewrite"
    return label, score, artifacts, errors, warnings


# --- self-test --------------------------------------------------------------

def self_test():
    """Every rule carries its own fixtures. A rule that cannot prove itself fails."""
    failures = []
    checked = 0
    for group in (ARTIFACTS, ERRORS, WARNINGS):
        for rule in group:
            try:
                rx = re.compile(rule["regex"])
            except re.error as exc:
                failures.append("%s: invalid regex: %s" % (rule["code"], exc))
                continue
            for sample in rule["must_match"]:
                checked += 1
                if not rx.search(sample):
                    failures.append("%s: must match but did not: %r" % (rule["code"], sample))
            for sample in rule["must_not_match"]:
                checked += 1
                if rx.search(sample):
                    failures.append("%s: false positive on: %r" % (rule["code"], sample))

    codes = [r["code"] for group in (ARTIFACTS, ERRORS, WARNINGS) for r in group]
    duplicates = sorted({c for c in codes if codes.count(c) > 1})
    if duplicates:
        failures.append("duplicate rule codes: %s" % ", ".join(duplicates))

    print("self-test: %d rules, %d fixtures" % (len(codes), checked))
    if failures:
        for line in failures:
            print("  FAIL  " + line)
        print("self-test: %d failure(s)" % len(failures))
        return 1
    print("self-test: ok")
    return 0


# --- cli --------------------------------------------------------------------

def read_input(path):
    if path and path != "-":
        with open(path, "r", encoding="utf-8") as fh:
            return fh.read()
    data = sys.stdin.buffer.read()
    return data.decode("utf-8", errors="replace")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("file", nargs="?", help="file to lint; omit to read stdin")
    parser.add_argument("--self-test", action="store_true", help="run the fixture suite and exit")
    parser.add_argument("--json", action="store_true", help="print findings as JSON")
    parser.add_argument("--allow", default="", metavar="CODE[,CODE]",
                        help="switch off these rules, for instance --allow when the writer's own "
                             "sample uses the punctuation a rule bans")
    args = parser.parse_args()

    if args.self_test:
        raise SystemExit(self_test())

    text = read_input(args.file)
    findings = lint(text, allow=args.allow.split(","))
    label, score, artifacts, errors, warnings = verdict(findings)

    if args.json:
        print(json.dumps({
            "verdict": label,
            "score": score,
            "counts": {
                "artifact": len(artifacts),
                "error": len(errors),
                "warning": len(warnings),
            },
            "findings": findings,
        }, ensure_ascii=False, indent=2))
    else:
        for f in findings:
            print("%s:%d  %-8s %-14s %s" % (
                args.file or "stdin", f["line"], f["severity"], f["code"], f["quote"]))
        print("")
        print("verdict: %s (score %d; %d artifact, %d error, %d warn)" % (
            label, score, len(artifacts), len(errors), len(warnings)))

    raise SystemExit(1 if (artifacts or errors) else 0)


if __name__ == "__main__":
    main()
